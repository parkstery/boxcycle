/**
 * 라이더를 **얼마나 자세히 그릴지** — 지도 줌 하나로 정한다.
 *
 * 왜 (2026-09-27) — 카메라 4단계(5m·60m·200m·전체) 중 뒤 둘은 라이더가 **점 하나**로
 * 보이는데, 렌더 경로에 줌 판단이 한 줄도 없어 네 단계가 똑같이 돌았다. 실측:
 *
 *     5m(zoom 23.7)   2.55 ms/프레임   그중 자세 계산 44%
 *     60m(zoom 20.1)  2.28 ms          43%
 *     200m(zoom 18.4) 2.39 ms          44%   ← 점인데 같은 값
 *     전체(낮은 zoom) 2.59 ms          42%   ← 점인데 같은 값
 *
 * 라이더 한 명당 값이고, 렌더 루프가 **사람 수만큼 전체 장면을 다시 그린다.**
 * 동행 5명이면 프레임 예산(16.7 ms)의 약 70% 를 라이더에만 쓴다 — 전부 점일 때도.
 *
 * ⚠️ **건너뛰는 것은 「그릴 때만 필요한 것」뿐이다.** 페달 위상·위치 적분 같은 상태 계산은
 * 계속 돈다(곱셈 몇 번이라 거의 공짜다). 그래서 다시 가까이 가도 **튀지 않고**, 첫 프레임
 * 한 번(≈2.4 ms)이면 평소 상태가 된다 — 예열이 필요한 종류가 아니다.
 */

/**
 * 이 줌 **미만**이면 자세(페달·다리 IK)를 새로 계산하지 않는다.
 *
 * 19 인 이유 — 실측 줌은 200m=18.4, 60m=20.1 이다. 그 사이에 선을 그어
 * **200m 이하(점)는 건너뛰고, 60m 이상(형태가 조금이라도 보이는 곳)은 그대로 둔다.**
 *
 * ⚠️ 이 값을 낮추면(=더 멀리서도 계산하면) 아끼는 것이 없어지고, 크게 올리면 60m 에서
 * 페달이 멈춘 것처럼 보인다. 바꿀 땐 위 실측 줌을 다시 재고 바꾼다.
 */
export const RIDER_POSE_ANIMATION_MIN_ZOOM = 19;

/**
 * 이 줌에서 라이더 자세를 새로 계산해야 하는가.
 *
 * 줌을 모르면(`null`·NaN) **계산한다** — 모를 때 건너뛰면 라이더가 조용히 멈춘다.
 * 안전한 쪽은 「그린다」다.
 */
export function shouldAnimateRiderPose(
  zoom: number | null | undefined,
  minZoom: number = RIDER_POSE_ANIMATION_MIN_ZOOM,
): boolean {
  if (typeof zoom !== "number" || !Number.isFinite(zoom)) return true;
  return zoom >= minZoom;
}
